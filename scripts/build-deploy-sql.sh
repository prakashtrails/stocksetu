#!/usr/bin/env bash
# Concatenate migrations + seed into one file to paste into the Supabase SQL Editor.
set -e
cd "$(dirname "$0")/.."
out=supabase/deploy-all.sql
{
  echo "-- StockSetu: full schema + demo data. Paste into Supabase → SQL Editor → Run."
  echo "-- Generated by scripts/build-deploy-sql.sh — do not edit by hand."
  for f in supabase/migrations/*.sql supabase/seed.sql supabase/seed_haldiram.sql; do
    echo; echo "-- ===== $f ====="; cat "$f"
  done
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)"

# Upgrade for a database that already has migrations 1-3 + the base seed.
up=supabase/deploy-02-haldiram.sql
{
  echo "-- StockSetu upgrade: plans/limits/accounts + Haldiram demo. Paste into SQL Editor → Run."
  for f in supabase/migrations/20261020000004_plans_and_accounts.sql supabase/seed_haldiram.sql; do
    echo; echo "-- ===== $f ====="; cat "$f"
  done
} > "$up"
echo "wrote $up ($(wc -c < "$up") bytes)"
